StyleDictionary.registerFormat({
  name: 'swiftui/primitives-font-families',
  formatter: ({ dictionary }) => {
    const familyTokens = dictionary.allTokens.filter(t => t.path[0] === 'fontFamily')

    const familyProperties = familyTokens
      .map(t => {
        const name = t.path[t.path.length - 1]
        const firstFont = t.value.split(',')[0].trim().replace(/"/g, '')
        return `    static let ${name}: String = { _ = _registered; return "${firstFont}" }()`
      })
      .join('\n')

    const allEntries = familyTokens
      .map(t => {
        const name = t.path[t.path.length - 1]
        return `        ("${name}", ${name})`
      })
      .join(',\n')

    const familyExtProps = familyTokens
      .map(t => {
        const name = t.path[t.path.length - 1]
        const prefixed = 'font' + name.charAt(0).toUpperCase() + name.slice(1)
        return `            public static let ${prefixed} = InstUI.Primitives.FontFamilies.${name}`
      })
      .join('\n')

    const familyExtension =
`public extension String {

    /// Access primitive font families via \`String.instui.primitives.fontLato\`
    enum instui {
        public enum primitives {
${familyExtProps}
        }
    }
}`

    // Triggers font registration exactly once when any font family is first accessed.
    // Private to the extension block — each font string property references it in its closure.
    const registrationTrigger = '    private static let _registered: Void = FontRegistration.registerFonts()'

    return [
      fileHeader,
      '',
      '// DO NOT EDIT — Auto-generated by `yarn build-instui`',
      'public extension InstUI.Primitives.FontFamilies {',
      registrationTrigger,
      '',
      familyProperties,
      '',
      '    static let all: [(name: String, family: String)] = [',
      allEntries,
      '    ]',
      '}',
      '',
      familyExtension,
      ''
    ].join('\n')
  }
})

