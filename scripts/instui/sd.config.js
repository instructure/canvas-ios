StyleDictionary.registerFormat({
  name: 'swiftui/primitives-colors',
  formatter: ({ dictionary }) => {
    const colorTokens = dictionary.allTokens.filter(t => t.path[0] === 'color')

    // Canonical Color declarations — hex lives here and nowhere else
    const colorProperties = colorTokens
      .map(t => {
        const name = t.path[t.path.length - 1]
        const hex = t.value.toUpperCase()
        const displayHex = hex.length === 9 && hex.endsWith('FF') ? hex.slice(0, 7) : hex
        return `    static let ${name} = Color(hex: "${displayHex}")`
      })
      .join('\n')

    const allEntries = colorTokens
      .map(t => {
        const name = t.path[t.path.length - 1]
        return `        ("${name}", ${name})`
      })
      .join(',\n')

    // Color extension — forwards to primitives, no hex duplication
    const colorExtProps = colorTokens
      .map(t => {
        const name = t.path[t.path.length - 1]
        return `            public static let ${name} = InstUI.Primitives.Colors.${name}`
      })
      .join('\n')

    // UIColor extension — wraps Color values via type-inferred dot syntax, no hex duplication
    const uiColorExtProps = colorTokens
      .map(t => {
        const name = t.path[t.path.length - 1]
        return `            public static let ${name} = UIColor(.instui.primitives.${name})`
      })
      .join('\n')

    const colorExtensions =
`public extension Color {

    /// Access primitive colors via \`Color.instui.primitives.navy120\`
    enum instui {
        public enum primitives {
${colorExtProps}
        }
    }
}

public extension UIColor {

    /// Access primitive colors via \`UIColor.instui.primitives.navy120\`
    enum instui {
        public enum primitives {
${uiColorExtProps}
        }
    }
}`

    return [
      fileHeader,
      '',
      'import SwiftUI',
      'import UIKit',
      '',
      '// DO NOT EDIT — Auto-generated by `yarn build-instui`',
      'public extension InstUI.Primitives.Colors {',
      colorProperties,
      '',
      '    static let all: [(name: String, color: Color)] = [',
      allEntries,
      '    ]',
      '}',
      '',
      colorExtensions,
      ''
    ].join('\n')
  }
})

