const colorExtension =
`extension Color {

    /// Supports the following syntax: \`.foregroundStyle(.instui.primitives.navy120)\`
    enum instui {
        static let primitives = InstUI.Primitives.Colors()
    }
}`

const sizeExtension =
`extension CGFloat {

    /// Supports the following syntax: \`.frame(width: .instui.primitives.size16)\`
    enum instui {
        static let primitives = InstUI.Primitives.Sizes()
    }
}`

StyleDictionary.registerFormat({
  name: 'swiftui/primitives-colors',
  formatter: ({ dictionary }) => {
    const colorTokens = dictionary.allTokens.filter(t => t.path[0] === 'color')

    const properties = colorTokens
      .map(t => {
        const name = t.path[t.path.length - 1]
        const hex = t.value.toUpperCase()
        const displayHex = hex.length === 9 && hex.endsWith('FF') ? hex.slice(0, 7) : hex
        return `        public let ${name} = Color(hex: "${displayHex}")`
      })
      .join('\n')

    return [
      fileHeader,
      '',
      'import SwiftUI',
      '',
      '// DO NOT EDIT — Auto-generated by \`yarn build-instui\`',
      'public extension InstUI.Primitives {',
      '    struct Colors: Sendable {',
      properties,
      '    }',
      '}',
      '',
      colorExtension,
      ''
    ].join('\n')
  }
})

StyleDictionary.registerFormat({
  name: 'swiftui/primitives-sizes',
  formatter: ({ dictionary }) => {
    const sizeTokens = dictionary.allTokens
      .filter(t => t.path[0] === 'size' || t.path[0] === 'additionalSize')
      .sort((a, b) => parseFloat(a.value) - parseFloat(b.value))

    const properties = sizeTokens
      .map(t => {
        const name = t.path[t.path.length - 1]
        const points = parseFloat(t.value) * 16
        return `        public let ${name}: CGFloat = ${points}`
      })
      .join('\n')

    return [
      fileHeader,
      '',
      'import CoreGraphics',
      '',
      '// DO NOT EDIT — Auto-generated by `yarn build-instui`',
      'public extension InstUI.Primitives {',
      '    struct Sizes: Sendable {',
      properties,
      '    }',
      '}',
      '',
      sizeExtension,
      ''
    ].join('\n')
  }
})

module.exports = function buildConfig(tokens) {
  return StyleDictionary.extend({
    tokens,
    platforms: {
      swift: {
        transforms: ['attribute/cti', 'color/hex8'],
        buildPath: 'packages/InstUI/Sources/InstUI/Sources/Primitives/',
        files: [
          {
            destination: 'InstUI.Primitives.Colors.swift',
            format: 'swiftui/primitives-colors'
          },
          {
            destination: 'InstUI.Primitives.Sizes.swift',
            format: 'swiftui/primitives-sizes'
          }
        ]
      }
    }
  })
}
