/*
Generates Swift files from semantic design token JSON files:

  packages/InstUI/Sources/Semantic/Generated/InstUI.Semantic.Color.swift
    — Nested Swift struct + build() for semantic Color tokens (light/dark pair)

  packages/InstUI/Sources/Semantic/Generated/InstUI.Semantic.<Section>.swift
    — Nested Swift struct + build() for each layout section (Size, Spacing, etc.)
    — Includes: size (including breakpoints/media, resolved as 1em = 16pt), spacing, borderRadius,
      borderWidth, fontSize, opacity, fontWeight, fontFamily
*/

const fs = require('fs')
const path = require('path')
const { fileHeader, isLeaf, toTypeName, genStructBlock, genInitLines, genAllEntries } = require('./sd.config.shared')

// ---------------------------------------------------------------------------
// Tree builder
// ---------------------------------------------------------------------------

// Build a lightweight tree from the JSON subtree.
// Each node is either:
//   {type: 'leaf'}
//   {type: 'node', children: {key: subtree, ...}}  (plain object, insertion-ordered)
function buildTree(obj) {
  if (isLeaf(obj)) {
    return { type: 'leaf' }
  }
  if (typeof obj !== 'object' || obj === null) {
    return { type: 'leaf' }
  }
  const children = {}
  for (const [k, v] of Object.entries(obj)) {
    if (typeof v === 'object' && v !== null) {
      children[k] = buildTree(v)
    }
  }
  return { type: 'node', children }
}

// ---------------------------------------------------------------------------
// File generator
// ---------------------------------------------------------------------------

// Generates a single `InstUI.Semantic.<typeName>.swift` containing:
//   • The public struct definition (via genStructBlock), with `all` as a stored property
//   • A static build() function that computes `all` at load time (shallow stack)
function generateSemanticFile({ typeName, tree, swiftImport, leafType }) {
  // When typeName === leafType (e.g. Color/Color), bare leafType inside the extension
  // on InstUI.Semantic.Color would shadow SwiftUI.Color. Qualify it with the module.
  const extLeafType = typeName === leafType
    ? `${swiftImport.replace('import ', '')}.${leafType}`
    : leafType
  const lines = []
  lines.push(fileHeader)
  lines.push('')
  lines.push(swiftImport)
  lines.push('')
  lines.push("// DO NOT EDIT — Auto-generated by `yarn build-instui`")

  // `all` is a stored property so it is computed once in build() at shallow call-stack
  // depth (colorLoader.load → build), not lazily from a deep SwiftUI render stack where
  // a 300-entry array literal would overflow the 512 KB thread stack.
  lines.push('extension InstUI.Semantic {')
  lines.push('')
  lines.push(genStructBlock(typeName, tree, 1, extLeafType, [
    `public let all: [(name: String, value: ${extLeafType})]`
  ]))
  lines.push('}')
  lines.push('')

  lines.push(`extension InstUI.Semantic.${typeName} {`)
  lines.push('')
  lines.push(`    static func build(_ token: (InstUI.TokenKey) throws -> ${extLeafType}) throws -> InstUI.Semantic.${typeName} {`)

  // Step 1: assign each top-level entry to a local variable so the `all` array can
  // reference them by name. build() is called from a shallow stack (≈10 frames, ~490 KB
  // free), so a large array literal is safe here — unlike accessing the computed property
  // from deep inside the SwiftUI render loop which only has ~200 KB remaining.
  const topEntries = Object.entries(tree.children)
  for (const [key, child] of topEntries) {
    if (child.type === 'leaf') {
      lines.push(`        let ${key} = try token("${key}")`)
    } else {
      const nestedType = toTypeName(key)
      const subLines = genInitLines(child, key, 2) // 2 → 8-space indent
      // subLines[0] is "        .init(" — prefix it with the variable declaration
      lines.push(`        let ${key} = try ${nestedType}${subLines[0].trimStart()}`)
      for (let j = 1; j < subLines.length; j++) lines.push(subLines[j])
    }
  }
  lines.push('')

  // Step 2: build `all` from the local variables
  lines.push(`        let all: [(name: String, value: ${extLeafType})] = [`)
  lines.push(...genAllEntries(tree, '', '', 3))
  lines.push('        ]')
  lines.push('')

  // Step 3: return the struct — no `try` needed here because all throwing calls are done
  lines.push(`        return InstUI.Semantic.${typeName}(`)
  for (const [key] of topEntries) {
    lines.push(`            ${key}: ${key},`)
  }
  lines.push('            all: all')
  lines.push('        )')
  lines.push('    }')

  lines.push('}')
  lines.push('')
  return lines.join('\n')
}

// ---------------------------------------------------------------------------
// Section configuration
// ---------------------------------------------------------------------------

// Each entry describes one top-level JSON section → one Swift file.
// excludeKeys removes sub-keys before building the tree (web-only values).
//
// Skipped sections (not included in LAYOUT_SECTIONS):
//   lineHeight  — mixed rem and % values; % lines can't be resolved without a base font size
//   visibleInCanvas / visibleInRebrand — design tool visibility flags, not runtime values
const COLOR_SECTION = {
  typeName: 'Color', swiftImport: 'import SwiftUI', leafType: 'Color'
}

const LAYOUT_SECTIONS = [
  { key: 'size', typeName: 'Size', swiftImport: 'import CoreGraphics', leafType: 'CGFloat' }, // includes breakpoints and media (em values resolved as 1em = 16pt)
  { key: 'spacing', typeName: 'Spacing', swiftImport: 'import CoreGraphics', leafType: 'CGFloat' },
  { key: 'borderRadius', typeName: 'BorderRadius', swiftImport: 'import CoreGraphics', leafType: 'CGFloat' },
  { key: 'borderWidth', typeName: 'BorderWidth', swiftImport: 'import CoreGraphics', leafType: 'CGFloat' },
  { key: 'fontSize', typeName: 'FontSize', swiftImport: 'import CoreGraphics', leafType: 'CGFloat' },
  { key: 'opacity', typeName: 'Opacity', swiftImport: 'import Foundation', leafType: 'Double' },
  { key: 'fontWeight', typeName: 'FontWeight', swiftImport: 'import SwiftUI', leafType: 'Font.Weight' },
  { key: 'fontFamily', typeName: 'FontFamily', swiftImport: 'import Foundation', leafType: 'String' },
]

// ---------------------------------------------------------------------------
// Module export
// ---------------------------------------------------------------------------

module.exports = function buildSemantic(light, dark, layout) {
  const sourcesDir = path.join(__dirname, '../../packages/InstUI/Sources/Semantic/Generated')
  fs.mkdirSync(sourcesDir, { recursive: true })

  // Color section — derived from light/dark JSON pair
  fs.writeFileSync(
    path.join(sourcesDir, 'InstUI.Semantic.Color.swift'),
    generateSemanticFile({ ...COLOR_SECTION, tree: buildTree(light.color) })
  )

  // Layout sections — all derived from layout/default.json
  for (const section of LAYOUT_SECTIONS) {
    let json = layout[section.key]
    if (!json) continue
    if (section.excludeKeys) {
      json = { ...json }
      for (const k of section.excludeKeys) delete json[k]
    }
    fs.writeFileSync(
      path.join(sourcesDir, `InstUI.Semantic.${section.typeName}.swift`),
      generateSemanticFile({ ...section, tree: buildTree(json) })
    )
  }
}
