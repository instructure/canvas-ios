            throw InstUI.TokenLoadError.missingFile("BaseButton.json not found in bundle")
        }
        let data = try Data(contentsOf: url)
        let leaves = try InstUI.TokenExtractor.extractLeaves(from: data, section: "baseButton")
        let resolver = InstUI.ComponentResolver(theme: theme, leaves: leaves)
