extension InstUI.Component.SharedTokens {

    static func load(using theme: InstUI.Theme) throws -> Self {
        guard let url = Bundle.module.url(forResource: "SharedTokens", withExtension: "json") else {
            throw InstUI.TokenLoadError.missingFile("SharedTokens.json not found in bundle")
        }
        let data = try Data(contentsOf: url)
        let leaves = try InstUI.TokenExtractor.extractLeaves(from: data, section: "sharedTokens")
        let resolver = InstUI.Component.Resolver(theme: theme, leaves: leaves)
        return try .build(
            dimension: resolver.dimension,
            color: resolver.color
        )
    }
}
