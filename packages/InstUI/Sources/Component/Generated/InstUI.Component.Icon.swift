extension InstUI.Component.Icon {

    static func load(using theme: InstUI.Theme) throws -> Self {
        guard let url = Bundle.module.url(forResource: "Icon", withExtension: "json") else {
            throw InstUI.TokenLoadError.missingFile("Icon.json not found in bundle")
        }
        let data = try Data(contentsOf: url)
        let leaves = try InstUI.TokenExtractor.extractLeaves(from: data, section: "icon")
        let resolver = InstUI.ComponentResolver(theme: theme, leaves: leaves)
        return try .build(
            dimension: resolver.dimension,
            color: resolver.color
        )
    }
}

